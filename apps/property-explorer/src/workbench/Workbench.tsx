// PE WORKBENCH CHASSIS (WB1) — the top-right BUBBLE CLUSTER + the ONE shared
// dock every tool opens into.
//
// THE DESIGN LAW (non-negotiable): the clean map-first PE stays the star; the
// cluster is the ONLY always-on element; every capability opens into this ONE
// dock (the space the property brief used — top-right, natural height); ONE
// tool open at a time — opening a bubble REPLACES the dock content; tapping
// the active bubble (or the dock's ×) closes the dock. Never two docks, never
// a split screen. Tool state persists PER-PROPERTY across open/close via
// useDockToolState (WorkbenchContext).
//
// PLACEMENT: the cluster hugs the top-right edge (top:12/right:12, a narrow
// vertical column of circular bubbles); the dock opens immediately to its
// LEFT in the brief's original space. The Find bar is top-center, the inspect
// card top-left, the MapToolset map-utility bubble bottom-right — the
// workbench covers none of them.
//
// LATER WAVES: add tools in registry.tsx through the WorkbenchToolDef contract
// (types.ts). Do NOT edit this file to add a tool.

import { useEffect, useState } from "react";
import type { CSSProperties, ReactNode } from "react";
import {
  dockLayoutStyle as resolveDockLayoutStyle,
  mobileToolPickerStyle,
  workbenchClusterStyle,
} from "../browse/mobile-layout";
import { useMobilePanel } from "../browse/MobilePanelContext";
import type { WorkbenchHostActions, WorkbenchToolDef } from "./types";
import { WorkbenchProvider } from "./WorkbenchContext";
import type { WorkbenchToolStateStore } from "./tool-state-store";

const CARD_BG = "var(--surface-card-translucent, rgba(13,17,23,0.94))";
const BORDER = "1px solid var(--surface-border-rgba, rgba(154,166,178,0.3))";
const TEXT = "var(--text-body, #e5e7eb)";
const MUTED = "var(--surface-muted, #94A3B8)";
const ACCENT = "var(--brand-blue, #3B82F6)"; // PRIMARY interactive hue (was cyan #7dd3fc)
const AMBER = "var(--semantic-warning, #F59E0B)"; // caution/notice (was raw yellow #fcd34d)

/**
 * Dock single-tenancy, as a pure rule: tapping the active bubble closes the
 * dock; tapping any other bubble REPLACES the dock content with that tool.
 */
export function nextOpenToolId(
  current: string | null,
  tapped: string,
): string | null {
  return current === tapped ? null : tapped;
}

/**
 * Dock POSITION/SIZE, as a pure rule (Fix A — expand-to-floating-box):
 *   COMPACT (default): hugs the top-right in the brief's original space
 *     (min 400px wide, viewport-height-capped).
 *   EXPANDED: a large floating box offset from the right edge with generous
 *     margins so the main map stays visible AROUND it — never full-screen —
 *     so a cramped report (the flood study map + legend especially) reads
 *     clearly. Extracted so the layout rule is unit-testable without a click
 *     harness (the file's `nextOpenToolId` pure-rule precedent).
 */
/** @deprecated import from mobile-layout.ts — kept for existing tests. */
export function dockLayoutStyle(isExpanded: boolean): CSSProperties {
  return resolveDockLayoutStyle(isExpanded, false);
}

/** 15px stroke glyph in the MapToolset icon language. */
export function WorkbenchIcon({ path }: { path: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={16}
      height={16}
      aria-hidden="true"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <path d={path} />
    </svg>
  );
}

function bubbleStyle(active: boolean, coming: boolean): CSSProperties {
  return {
    display: "inline-flex",
    alignItems: "center",
    justifyContent: "center",
    width: 34,
    height: 34,
    borderRadius: "50%",
    cursor: "pointer",
    color: active ? "#0b0f14" : coming ? MUTED : TEXT,
    background: active ? ACCENT : CARD_BG,
    border: active ? `1px solid ${ACCENT}` : BORDER,
    boxShadow: "0 4px 14px rgba(0,0,0,0.35)",
    transition: "background 120ms ease, color 120ms ease",
  };
}

export interface WorkbenchProps {
  /** The tool registry (registry.tsx). Order = cluster order, top to bottom. */
  tools: WorkbenchToolDef[];
  /** The single open tool (null → dock closed). Owned by the app shell. */
  openToolId: string | null;
  onOpenToolChange: (next: string | null) => void;
  /** Active property = inspected parcel's node id, else the subject's. */
  activeParcelNodeId: string | null;
  host: WorkbenchHostActions;
  /** Injectable for tests; defaults to the app-wide singleton store. */
  store?: WorkbenchToolStateStore;
}

/**
 * The chassis surface: bubble cluster (always on) + the one shared dock
 * (rendered only while a tool is open). Mount ONCE in ExplorerMap.
 */
export function Workbench({
  tools,
  openToolId,
  onOpenToolChange,
  activeParcelNodeId,
  host,
  store,
}: WorkbenchProps) {
  const { isMobile, activeSheet, openSheet } = useMobilePanel();
  const mobileResearchOpen = isMobile && activeSheet === "research";
  const openTool = openToolId
    ? (tools.find((t) => t.id === openToolId) ?? null)
    : null;
  const closeDock = () => onOpenToolChange(null);

  // EXPAND-TO-FLOATING-BOX (general pattern for every right-side report/tool):
  // the dock can enlarge to a large floating box that keeps the map visible
  // around it — NOT full-screen — so cramped report content (the flood study
  // map thumbnail + legend especially) becomes clearly readable. Expand state
  // is transient: it resets whenever the open tool changes or the dock closes
  // (a fresh tool always opens at the compact size). Only tools that opt in
  // (`expandable`, default true) show the control.
  const [expanded, setExpanded] = useState(false);
  useEffect(() => {
    // Reset on tool switch / close — never carry an expanded box into the
    // next tool or a closed dock.
    setExpanded(false);
  }, [openToolId]);
  const canExpand = openTool ? openTool.expandable !== false : false;
  const isExpanded = expanded && canExpand;

  return (
    <WorkbenchProvider
      activeParcelNodeId={activeParcelNodeId}
      closeDock={closeDock}
      host={host}
      store={store}
    >
      {/* THE BUBBLE CLUSTER — the only always-on workbench element. Pushed
          DOWN below the MapLibre zoom/compass NavigationControl (added
          top-right in map-renderer.js): the control stack is ~10px margin +
          three ~29px buttons ≈ 100px, so the cluster starts at top:118 to
          clear it and the two upper-right chrome elements no longer overlap.
          zIndex raised 9 → 11 so these SMALL bubbles sit in front of the large
          right-side dock (zIndex 9) per the small-in-front-of-large rule. */}
      <div
        data-testid="workbench-cluster"
        style={workbenchClusterStyle(isMobile)}
      >
        {tools.map((tool) => {
          const active = tool.id === openToolId;
          return (
            <button
              key={tool.id}
              type="button"
              data-testid={`workbench-bubble-${tool.id}`}
              title={tool.status === "coming" ? `${tool.label} — coming` : tool.label}
              aria-label={tool.label}
              aria-pressed={active}
              onClick={() => onOpenToolChange(nextOpenToolId(openToolId, tool.id))}
              style={bubbleStyle(active, tool.status === "coming")}
            >
              {tool.icon}
            </button>
          );
        })}
      </div>

      {/* Mobile research sheet — horizontal tool picker (replaces top-right cluster). */}
      {isMobile && mobileResearchOpen && !isExpanded && (
        <div
          data-testid="workbench-mobile-picker"
          style={mobileToolPickerStyle()}
        >
          {tools.map((tool) => {
            const active = tool.id === openToolId;
            return (
              <button
                key={tool.id}
                type="button"
                data-testid={`workbench-mobile-bubble-${tool.id}`}
                aria-label={tool.label}
                aria-pressed={active}
                title={tool.label}
                onClick={() => {
                  openSheet("research");
                  onOpenToolChange(nextOpenToolId(openToolId, tool.id));
                }}
                style={{
                  ...bubbleStyle(active, tool.status === "coming"),
                  flexShrink: 0,
                }}
              >
                {tool.icon}
              </button>
            );
          })}
        </div>
      )}

      {/* THE ONE SHARED DOCK — exactly one tool's content, or nothing.
          HEIGHT MODEL (polish wave): the dock never extends past the viewport.
          maxHeight = 100vh minus the dock's top offset (12px) minus a 16px
          bottom margin; content taller than that scrolls INSIDE the dock
          (momentum scroll) while the header (title + ×) stays pinned. This is
          dock chrome, owned HERE for every tool — tools do not add their own
          outer scrollboxes. */}
      {openTool && (!isMobile || mobileResearchOpen) && (
        <section
          data-testid="workbench-dock"
          data-tool={openTool.id}
          data-expanded={isExpanded ? "1" : undefined}
          data-mobile-dock={isMobile ? "1" : undefined}
          style={{
            position: isMobile ? "fixed" : "absolute",
            zIndex: isMobile ? 15 : 9,
            ...resolveDockLayoutStyle(isExpanded, isMobile),
            display: "flex",
            flexDirection: "column",
            overflow: "hidden",
            borderRadius: isMobile ? undefined : 8,
            color: TEXT,
            background: CARD_BG,
            border: isMobile ? "none" : BORDER,
            borderTop: isMobile ? BORDER : undefined,
            font: "12px/1.45 system-ui, -apple-system, Segoe UI, Roboto, sans-serif",
            animation: "pe-dock-in 240ms ease",
          }}
        >
          <style>{`@keyframes pe-dock-in {
  from { opacity: 0; transform: translateY(-10px); }
  to   { opacity: 1; transform: translateY(0); }
}`}</style>
          {/* PINNED HEADER — never scrolls out of view. */}
          <div
            data-testid="dock-header"
            style={{
              flex: "0 0 auto",
              display: "flex",
              justifyContent: "space-between",
              alignItems: "center",
              gap: 8,
              padding: "10px 14px 6px",
              marginBottom: 8,
              borderBottom: "1px solid rgba(154,166,178,0.2)",
            }}
          >
            <strong style={{ fontSize: 12.5 }}>{openTool.label}</strong>
            <div style={{ display: "flex", alignItems: "center", gap: 10 }}>
              {canExpand && (
                <button
                  type="button"
                  aria-label={isExpanded ? "Collapse report" : "Expand report"}
                  aria-pressed={isExpanded}
                  title={
                    isExpanded
                      ? "Collapse to the compact panel"
                      : "Expand to a large readable view (map stays visible)"
                  }
                  data-testid="dock-expand"
                  onClick={() => setExpanded((v) => !v)}
                  style={{
                    display: "inline-flex",
                    background: "transparent",
                    border: "none",
                    color: MUTED,
                    cursor: "pointer",
                    padding: 0,
                    lineHeight: 1,
                  }}
                >
                  <svg
                    viewBox="0 0 24 24"
                    width={15}
                    height={15}
                    aria-hidden="true"
                    fill="none"
                    stroke="currentColor"
                    strokeWidth={2}
                    strokeLinecap="round"
                    strokeLinejoin="round"
                  >
                    {isExpanded ? (
                      <path d="M15 9h4m0 0V5m0 4-5-5M9 15H5m0 0v4m0-4 5 5" />
                    ) : (
                      <path d="M15 3h6m0 0v6m0-6-7 7M9 21H3m0 0v-6m0 6 7-7" />
                    )}
                  </svg>
                </button>
              )}
              <button
                type="button"
                aria-label="Close"
                data-testid="dock-close"
                onClick={closeDock}
                style={{
                  background: "transparent",
                  border: "none",
                  color: MUTED,
                  cursor: "pointer",
                  fontSize: 15,
                  lineHeight: 1,
                  padding: 0,
                }}
              >
                ×
              </button>
            </div>
          </div>
          {/* THE SCROLL REGION — every tool's content lives inside it. */}
          <div
            data-testid="dock-scroll"
            style={{
              flex: "1 1 auto",
              minHeight: 0,
              overflowY: "auto",
              WebkitOverflowScrolling: "touch",
              padding: "0 14px 14px",
            }}
          >
            <DockBody
              tool={openTool}
              activeParcelNodeId={activeParcelNodeId}
              closeDock={closeDock}
              host={host}
            />
          </div>
        </section>
      )}
    </WorkbenchProvider>
  );
}

/** The dock's honest-state gate, then the tool's own content. */
function DockBody({
  tool,
  activeParcelNodeId,
  closeDock,
  host,
}: {
  tool: WorkbenchToolDef;
  activeParcelNodeId: string | null;
  closeDock: () => void;
  host: WorkbenchHostActions;
}): ReactNode {
  // Registered-but-not-live: an HONEST coming state — never dead-looking UI.
  if (tool.status === "coming" || !tool.render) {
    return (
      <p
        data-testid="dock-coming"
        style={{ margin: 0, color: MUTED, fontSize: 11.5 }}
      >
        {tool.label} is registered on the workbench but not wired up yet —
        nothing here is live. It arrives in a later build wave.
      </p>
    );
  }
  // Property-scoped tool with no active property: honest, actionable state.
  if (tool.propertyScoped && !activeParcelNodeId) {
    return (
      <p
        data-testid="dock-no-property"
        style={{ margin: 0, color: AMBER, fontSize: 11.5 }}
      >
        Select a property first — click a parcel on the map (or use search) and
        {" "}
        {tool.label.toLowerCase()} will scope to it.
      </p>
    );
  }
  return tool.render({ activeParcelNodeId, closeDock, host });
}
