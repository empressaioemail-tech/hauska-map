// apps/property-explorer/src/workbench/Workbench.tsx
//
// PE WORKBENCH CHASSIS (WB1) — the top-right BUBBLE CLUSTER + the ONE shared
// dock every tool opens into.
//
// THE DESIGN LAW (non-negotiable): the clean map-first PE stays the star; the
// cluster is the ONLY always-on element; every capability opens into this ONE
// dock (the space the property brief used — top-right, natural height); ONE
// tool open at a time — opening a bubble REPLACES the dock content; tapping
// the active bubble (or the dock's ×) closes the dock. Never two docks, never
// a split screen. Tool state persists PER-PROPERTY across open/close via
// useDockToolState (WorkbenchContext).
//
// PLACEMENT: the cluster hugs the top-right edge (top:12/right:12, a narrow
// vertical column of circular bubbles); the dock opens immediately to its
// LEFT in the brief's original space. The Find bar is top-center, the inspect
// card top-left, the MapToolset map-utility bubble bottom-right — the
// workbench covers none of them.
//
// LATER WAVES: add tools in registry.tsx through the WorkbenchToolDef contract
// (types.ts). Do NOT edit this file to add a tool.

import type { CSSProperties, ReactNode } from "react";
import type { WorkbenchHostActions, WorkbenchToolDef } from "./types";
import { WorkbenchProvider } from "./WorkbenchContext";
import type { WorkbenchToolStateStore } from "./tool-state-store";

const CARD_BG = "rgba(13,17,23,0.94)";
const BORDER = "1px solid rgba(154,166,178,0.35)";
const TEXT = "#e5e7eb";
const MUTED = "#9aa6b2";
const ACCENT = "#7dd3fc";
const AMBER = "#fcd34d";

/**
 * Dock single-tenancy, as a pure rule: tapping the active bubble closes the
 * dock; tapping any other bubble REPLACES the dock content with that tool.
 */
export function nextOpenToolId(
  current: string | null,
  tapped: string,
): string | null {
  return current === tapped ? null : tapped;
}

/** 15px stroke glyph in the MapToolset icon language. */
export function WorkbenchIcon({ path }: { path: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={16}
      height={16}
      aria-hidden="true"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <path d={path} />
    </svg>
  );
}

function bubbleStyle(active: boolean, coming: boolean): CSSProperties {
  return {
    display: "inline-flex",
    alignItems: "center",
    justifyContent: "center",
    width: 34,
    height: 34,
    borderRadius: "50%",
    cursor: "pointer",
    color: active ? "#0b0f14" : coming ? MUTED : TEXT,
    background: active ? ACCENT : CARD_BG,
    border: active ? `1px solid ${ACCENT}` : BORDER,
    boxShadow: "0 4px 14px rgba(0,0,0,0.35)",
    transition: "background 120ms ease, color 120ms ease",
  };
}

export interface WorkbenchProps {
  /** The tool registry (registry.tsx). Order = cluster order, top to bottom. */
  tools: WorkbenchToolDef[];
  /** The single open tool (null → dock closed). Owned by the app shell. */
  openToolId: string | null;
  onOpenToolChange: (next: string | null) => void;
  /** Active property = inspected parcel's node id, else the subject's. */
  activeParcelNodeId: string | null;
  host: WorkbenchHostActions;
  /** Injectable for tests; defaults to the app-wide singleton store. */
  store?: WorkbenchToolStateStore;
}

/**
 * The chassis surface: bubble cluster (always on) + the one shared dock
 * (rendered only while a tool is open). Mount ONCE in ExplorerMap.
 */
export function Workbench({
  tools,
  openToolId,
  onOpenToolChange,
  activeParcelNodeId,
  host,
  store,
}: WorkbenchProps) {
  const openTool = openToolId
    ? (tools.find((t) => t.id === openToolId) ?? null)
    : null;
  const closeDock = () => onOpenToolChange(null);

  return (
    <WorkbenchProvider
      activeParcelNodeId={activeParcelNodeId}
      closeDock={closeDock}
      host={host}
      store={store}
    >
      {/* THE BUBBLE CLUSTER — the only always-on workbench element. */}
      <div
        data-testid="workbench-cluster"
        style={{
          position: "absolute",
          top: 12,
          right: 12,
          zIndex: 9,
          display: "flex",
          flexDirection: "column",
          gap: 7,
        }}
      >
        {tools.map((tool) => {
          const active = tool.id === openToolId;
          return (
            <button
              key={tool.id}
              type="button"
              data-testid={`workbench-bubble-${tool.id}`}
              title={tool.status === "coming" ? `${tool.label} — coming` : tool.label}
              aria-label={tool.label}
              aria-pressed={active}
              onClick={() => onOpenToolChange(nextOpenToolId(openToolId, tool.id))}
              style={bubbleStyle(active, tool.status === "coming")}
            >
              {tool.icon}
            </button>
          );
        })}
      </div>

      {/* THE ONE SHARED DOCK — exactly one tool's content, or nothing. */}
      {openTool && (
        <section
          data-testid="workbench-dock"
          data-tool={openTool.id}
          style={{
            position: "absolute",
            top: 12,
            right: 54,
            zIndex: 9,
            width: "min(400px, calc(100vw - 78px))",
            borderRadius: 8,
            color: TEXT,
            background: CARD_BG,
            border: BORDER,
            padding: "10px 14px 14px",
            font: "12px/1.45 system-ui, -apple-system, Segoe UI, Roboto, sans-serif",
            animation: "pe-dock-in 240ms ease",
          }}
        >
          <style>{`@keyframes pe-dock-in {
  from { opacity: 0; transform: translateY(-10px); }
  to   { opacity: 1; transform: translateY(0); }
}`}</style>
          <div
            style={{
              display: "flex",
              justifyContent: "space-between",
              alignItems: "center",
              gap: 8,
              marginBottom: 8,
              paddingBottom: 6,
              borderBottom: "1px solid rgba(154,166,178,0.2)",
            }}
          >
            <strong style={{ fontSize: 12.5 }}>{openTool.label}</strong>
            <button
              type="button"
              aria-label="Close"
              data-testid="dock-close"
              onClick={closeDock}
              style={{
                background: "transparent",
                border: "none",
                color: MUTED,
                cursor: "pointer",
                fontSize: 15,
                lineHeight: 1,
                padding: 0,
              }}
            >
              ×
            </button>
          </div>
          <DockBody
            tool={openTool}
            activeParcelNodeId={activeParcelNodeId}
            closeDock={closeDock}
            host={host}
          />
        </section>
      )}
    </WorkbenchProvider>
  );
}

/** The dock's honest-state gate, then the tool's own content. */
function DockBody({
  tool,
  activeParcelNodeId,
  closeDock,
  host,
}: {
  tool: WorkbenchToolDef;
  activeParcelNodeId: string | null;
  closeDock: () => void;
  host: WorkbenchHostActions;
}): ReactNode {
  // Registered-but-not-live: an HONEST coming state — never dead-looking UI.
  if (tool.status === "coming" || !tool.render) {
    return (
      <p
        data-testid="dock-coming"
        style={{ margin: 0, color: MUTED, fontSize: 11.5 }}
      >
        {tool.label} is registered on the workbench but not wired up yet —
        nothing here is live. It arrives in a later build wave.
      </p>
    );
  }
  // Property-scoped tool with no active property: honest, actionable state.
  if (tool.propertyScoped && !activeParcelNodeId) {
    return (
      <p
        data-testid="dock-no-property"
        style={{ margin: 0, color: AMBER, fontSize: 11.5 }}
      >
        Select a property first — click a parcel on the map (or use search) and
        {" "}
        {tool.label.toLowerCase()} will scope to it.
      </p>
    );
  }
  return tool.render({ activeParcelNodeId, closeDock, host });
}
