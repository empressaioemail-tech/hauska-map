/**
 * Dock single-tenancy, as a pure rule: tapping the active bubble closes the
 * dock; tapping any other bubble REPLACES the dock content with that tool.
 */
export function nextOpenToolId(
  current: string | null,
  tapped: string,
): string | null {
  return current === tapped ? null : tapped;
}

/**
 * Left map-utility stack only (draw / layers / notifications). Workbench
 * tools must use nextOpenToolId — never this.
 */
export function nextOpenToolIds(current: string[], tapped: string): string[] {
  return current.includes(tapped)
    ? current.filter((id) => id !== tapped)
    : [...current, tapped];
}

/** Sentinel: no reconcile has run yet. Distinct from null, which is a legal
 *  openToolId meaning "the column is closed". */
const NEVER_SYNCED = Symbol("never-synced");

/** Workbench docks on the right. Left stacking is MapToolset, not this chassis. */
export const DEFAULT_DOCK_SIDE = "right" as const;

/**
 * Dock POSITION/SIZE, as a pure rule (Fix A — expand-to-floating-box):
 *   COMPACT (default): hugs the top-right in the brief's original space
 *     (min 400px wide, viewport-height-capped).
 *   EXPANDED: a large floating box offset from the right edge with generous
 *     margins so the main map stays visible AROUND it — never full-screen —
 *     so a cramped report (the flood study map + legend especially) reads
 *     clearly. Extracted so the layout rule is unit-testable without a click
 *     harness (the file's `nextOpenToolId` pure-rule precedent).
 */
/** @deprecated import from mobile-layout.ts — kept for existing tests. */
export function dockLayoutStyle(isExpanded: boolean): CSSProperties {
  return resolveDockLayoutStyle(isExpanded, false);
}

/** 15px stroke glyph at 1.7 — the v2 rail weight. */
export function WorkbenchIcon({ path }: { path: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={15}
      height={15}
      aria-hidden="true"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <path d={path} />
    </svg>
  );
}

/**
 * A rail bubble INSIDE the capsule.
 *
 * The capsule (workbenchClusterStyle) owns the edge, the fill and the shadow.
 * A bubble therefore has none of its own — it is a transparent 34px circle
 * that tints on hover and on open. That is the whole difference between the
 * kit-04 rail and the column of seven separately-bordered buttons it replaces.
 *
 *   rest   transparent, glyph at 58% white
 *   hover  9% white, glyph to pure white
 *   open   14% white, BLUE GLYPH — no blue fill anywhere (operator ruling
 *          2026-08-27: the blue slab is an eyesore). The open state is read
 *          from the glyph and the lift, not from a coloured ground.
 *   coming glyph at 30%, half opacity
 *
 * Never a count badge, never a red dot, never a scale transform on hover.
 */
function bubbleStyle(active: boolean, coming: boolean): CSSProperties {
  return {
    display: "inline-flex",
    alignItems: "center",
    justifyContent: "center",
    position: "relative",
    padding: 0,
    width: PE.bubble,
    height: PE.bubble,
    borderRadius: "50%",
    cursor: "pointer",
    color: active
      ? PE.blue
      : coming
        ? "rgba(255,255,255,.30)"
        : "rgba(255,255,255,.58)",
    background: active ? "rgba(255,255,255,.14)" : "transparent",
    border: "none",
    boxShadow: "none",
    opacity: coming ? 0.5 : 1,
    transition: `background ${MOTION.state}, color ${MOTION.state}, opacity ${MOTION.state}`,
  };
}

export interface WorkbenchProps {
  /** The tool registry (registry.tsx). Order = cluster order, top to bottom. */
  tools: WorkbenchToolDef[];
  /** The single open tool (null → dock closed). Owned by the app shell. */
  openToolId: string | null;
  onOpenToolChange: (next: string | null) => void;
  /**
   * Ignored for workbench tools. Kept so a caller cannot revive left
   * multi-open by passing an array — nextOpenToolId is the only rule.
   */
  openToolIds?: string[];
  onOpenToolIdsChange?: (next: string[]) => void;
  /** Always "right" for workbench docks. Default is right. */
  dockSide?: "left" | "right";
  /** Inspect card rendered inside the brief dock (desktop, right rail). */
  inspectSlot?: ReactNode;
  /** Active property = inspected parcel's node id, else the subject's. */
  activeParcelNodeId: string | null;
  host: WorkbenchHostActions;
  /** Injectable for tests; defaults to the app-wide singleton store. */
  store?: WorkbenchToolStateStore;
  /**
   * Seeds the dock stack. TEST SEAM, mirroring `store` above: this repo runs
   * vitest in a node environment with no click harness, so the only way to
   * prove the chassis RENDERS a stack (as opposed to proving the rules in
   * dock-stack.ts, which is a separate thing) is to hand it one. Production
   * never passes it; the stack builds from taps.
   */
  initialOpenIds?: string[];
  /** Seeds which of them are folded. TEST SEAM, same reason as above. */
  initialFoldedIds?: string[];
  /** Surfaces that need the chassis context (inspect-card brief). */
  children?: ReactNode;
}

/**
 * The chassis surface: bubble cluster (always on) + the one shared dock
 * (rendered only while a tool is open). Mount ONCE in ExplorerMap.
 */
export function Workbench({
  tools,
  openToolId,
  onOpenToolChange,
  openToolIds: _ignoredOpenToolIds,
  onOpenToolIdsChange: _ignoredOnOpenToolIdsChange,
  dockSide = DEFAULT_DOCK_SIDE,
  inspectSlot,
  activeParcelNodeId,
  host,
  store,
  initialOpenIds,
  initialFoldedIds,
  children,
}: WorkbenchProps) {
  const { isMobile, activeSheet, openSheet } = useMobilePanel();
  const mobileResearchOpen = isMobile && activeSheet === "research";
  const railTools = tools.filter((t) => t.inCluster !== false);
  void _ignoredOpenToolIds;
  void _ignoredOnOpenToolIdsChange;
  void dockSide;

  // THE STACK. The shell still owns ONE `openToolId` — that is the expanded
  // tool — and this chassis owns which other tools are open behind it. Keeping
  // the shell's prop shape unchanged is what let stacking land without
  // rewriting ExplorerMap's state or its ensureWorkbenchTool callers.
  const [stack, setStack] = useState<DockStack>(() =>
    initialOpenIds && initialOpenIds.length > 0
      ? { open: initialOpenIds, folded: initialFoldedIds ?? [] }
      : EMPTY_STACK,
  );
  const known = useMemo(() => new Set(tools.map((t) => t.id)), [tools]);

  // Reconcile in render, not in an effect: an effect would paint one frame of
  // the wrong stack every time the shell opens a tool (ensureWorkbenchTool on
  // a parcel click), which reads as a flicker.
  // THE SHELL'S openToolId IS AN EVENT, NOT A STANDING ORDER.
  //
  // syncStack unfolds the tool it is given, which is right when the shell is
  // ASKING for a tool (a parcel click calling ensureWorkbenchTool("brief")
  // means: make the brief readable). It is wrong to re-apply on every render,
  // because openToolId keeps naming the newest open dock long after that
  // request. Folding the newest dock therefore un-folded itself on the very
  // next paint, and with only ONE dock open that dock is always the newest —
  // so folding appeared to do nothing at all.
  //
  // Sync only when the value CHANGES. A repeat of the same id is the stale
  // standing value, not a new request, and must not overrule a fold the user
  // just performed.
  // A SEEDED stack is already post-sync: `initialOpenIds` hands us the state a
  // user would have built by tapping, folds included, so re-syncing it on the
  // first render would undo those folds — the exact bug this guards.
  const lastSyncedRef = useRef<string | null | typeof NEVER_SYNCED>(
    initialOpenIds && initialOpenIds.length > 0 ? openToolId : NEVER_SYNCED,
  );
  const isNewRequest = lastSyncedRef.current !== openToolId;
  const synced = pruneStack(
    isNewRequest ? syncStack(stack, openToolId) : stack,
    known,
  );
  lastSyncedRef.current = openToolId;
  if (synced !== stack) {
    // Same-render state catch-up. Legal, and cheaper than the extra paint.
    setStack(synced);
  }

  // Mobile keeps ONE sheet: stacking is a desktop-column behaviour and a
  // stack of folded headers on a phone is worse than a single sheet.
  // Mobile keeps ONE sheet: a stack of docks on a phone is worse than one.
  const newest = newestOpen(synced);
  const stackedIds = isMobile ? (newest ? [newest] : []) : synced.open;
  const openIds = synced.open;
  const openTool = newest ? (tools.find((t) => t.id === newest) ?? null) : null;

  const applyStack = (next: DockStack) => {
    setStack(next);
    // The shell tracks ONE id. It is the newest open tool, which is what
    // "which tool is the user working in" means once several can be open.
    const nextNewest = newestOpen(next);
    if (nextNewest !== openToolId) onOpenToolChange(nextNewest);
  };
  const tapBubble = (id: string) => applyStack(tapDock(synced, id));
  const foldOne = (id: string) => applyStack(toggleFold(synced, id));
  const closeOne = (id: string) => applyStack(closeOneDock(synced, id));
  // The dock-level close a TOOL calls through WorkbenchContext closes the
  // newest dock, not the whole column.
  const closeDock = () => {
    if (newest) applyStack(closeOneDock(synced, newest));
    else onOpenToolChange(null);
  };

  // EXPAND-TO-FLOATING-BOX (general pattern for every right-side report/tool):
  // the dock can enlarge to a large floating box that keeps the map visible
  // around it — NOT full-screen — so cramped report content (the flood study
  // map thumbnail + legend especially) becomes clearly readable. Expand state
  // is transient: it resets whenever the open tool changes or the dock closes
  // (a fresh tool always opens at the compact size). Only tools that opt in
  // (`expandable`, default true) show the control.
  const [expanded, setExpanded] = useState(false);
  useEffect(() => {
    // Width belongs to the COLUMN, so it must NOT reset every time another
    // tool opens — that would snap the column narrow under the user mid-read.
    // It resets only when the column empties, which is the one moment the
    // setting has nothing left to apply to.
    if (openToolId === null) setExpanded(false);
  }, [openToolId]);
  const canExpand = openTool ? openTool.expandable !== false : false;
  const isExpanded = expanded && canExpand;

  return (
    <WorkbenchProvider
      activeParcelNodeId={activeParcelNodeId}
      closeDock={closeDock}
      host={host}
      store={store}
    >
      {children}
      {/* THE BUBBLE CLUSTER — the only always-on workbench element. Pushed
          DOWN below the MapLibre zoom/compass NavigationControl (added
          top-right in map-renderer.js): the control stack is ~10px margin +
          three ~29px buttons ≈ 100px, so the cluster starts at top:118 to
          clear it and the two upper-right chrome elements no longer overlap.
          zIndex raised 9 → 11 so these SMALL bubbles sit in front of the large
          right-side dock (zIndex 9) per the small-in-front-of-large rule. */}
      <div
        data-testid="workbench-cluster"
        style={workbenchClusterStyle(isMobile)}
      >
        {railTools.map((tool) => {
          const active = openIds.includes(tool.id);
          return (
            <BubbleTip
              key={tool.id}
              side="left"
              label={
                tool.status === "coming"
                  ? `${tool.label} · coming soon`
                  : tool.unread
                    ? `${tool.label} · new`
                    : tool.label
              }
            >
              <button
                type="button"
                className="ss-bubble pe-btn"
                data-open={active ? "1" : undefined}
                data-coming={tool.status === "coming" ? "1" : undefined}
                data-testid={`workbench-bubble-${tool.id}`}
                aria-label={tool.unread ? `${tool.label} — new` : tool.label}
                aria-pressed={active}
                onClick={() => tapBubble(tool.id)}
                style={bubbleStyle(active, tool.status === "coming")}
              >
                {tool.icon}
                {/* THE GOLD UNREAD DOT. Operator ruling 2026-08-27, taken
                    against my recommendation and recorded as such: gold, not
                    the blue the original v2 SPEC named. It is the one place
                    gold appears that is not the brand mark, and the
                    chrome-kit gate carries a narrow carve-out naming this
                    file. Never a count badge — the dot says something landed,
                    the tooltip label says what. */}
                {tool.unread ? (
                  <span
                    data-testid={`workbench-unread-${tool.id}`}
                    aria-hidden
                    style={{
                      position: "absolute",
                      top: 5,
                      right: 5,
                      width: 7,
                      height: 7,
                      borderRadius: "50%",
                      background: PE.gold,
                      boxShadow:
                        "0 0 0 2px rgba(11,14,19,.95), 0 0 8px 1px rgba(232,150,59,.85)",
                    }}
                  />
                ) : null}
              </button>
            </BubbleTip>
          );
        })}
      </div>

      {/* Mobile research sheet — horizontal tool picker (replaces top-right cluster). */}
      {isMobile && mobileResearchOpen && !isExpanded && (
        <div
          data-testid="workbench-mobile-picker"
          style={mobileToolPickerStyle()}
        >
          {railTools.map((tool) => {
            const active = openIds.includes(tool.id);
            return (
              <button
                key={tool.id}
                type="button"
                className="ss-bubble pe-btn"
                data-open={active ? "1" : undefined}
                data-coming={tool.status === "coming" ? "1" : undefined}
                data-testid={`workbench-mobile-bubble-${tool.id}`}
                aria-label={tool.label}
                aria-pressed={active}
                onClick={() => {
                  openSheet("research");
                  tapBubble(tool.id);
                }}
                style={{
                  ...bubbleStyle(active, tool.status === "coming"),
                  flexShrink: 0,
                }}
              >
                {tool.icon}
              </button>
            );
          })}
        </div>
      )}

      {/* THE DOCK COLUMN. Every open tool lives here, oldest at the top. The
          newest is expanded; the rest fold to their 36px header and stay one
          click away. Nothing is closed on the user's behalf.

          The expand-to-floating-box case leaves the column entirely: that tool
          becomes the large readable box while the others stay stacked behind
          it, so a flood study can be read full-size without losing the chat
          you had open beside it. */}
      {stackedIds.length > 0 && (!isMobile || mobileResearchOpen) && (
        <div
          data-testid="workbench-dock-column"
          className="pe-scroll"
          data-count={stackedIds.length}
          style={
            isMobile
              ? {
                  position: "fixed",
                  zIndex: 15,
                  ...resolveDockLayoutStyle(false, true),
                }
              : {
                  position: "absolute",
                  zIndex: 9,
                  // WIDTH IS THE COLUMN'S, not one dock's. Expanding widens
                  // the whole column so every open dock grows together and
                  // none can land on top of another.
                  // ONE SOURCE OF TRUTH for the column geometry.
                  // This block used to hardcode top/right/width, which meant
                  // dockLayoutStyle stopped driving the desktop column the
                  // moment the stack was introduced: the widening to 380 and
                  // the move to right:74 both landed in the rule, passed their
                  // tests, and never reached the screen. A value with two
                  // owners has no owner.
                  ...resolveDockLayoutStyle(isExpanded, false),
                  display: "flex",
                  flexDirection: "column",
                  gap: 8,
                  overflowY: "auto",
                  pointerEvents: "none",
                }
          }
        >
          {stackedIds.map((id) => {
            const tool = tools.find((t) => t.id === id);
            if (!tool) return null;
            // EVERY open dock is expanded unless the user folded THAT dock.
            // No dock folds because another one opened.
            const isOpen = isExpandedIn(synced, id);
            // No dock leaves the column any more. `boxed` used to lift one
            // out into a fixed floating box at its own width, which is what
            // made them overlap.
            // Any dock can be folded, including the only one — folding is the
            // user putting something aside, not a side effect of a count.
            const foldable = !isMobile;
            return (
              <section
                key={id}
                data-testid="workbench-dock"
                data-tool={tool.id}
                data-dock-side={DEFAULT_DOCK_SIDE}
                data-folded={!isOpen ? "1" : undefined}
                data-expanded={isExpanded ? "1" : undefined}
                data-mobile-dock={isMobile ? "1" : undefined}
                data-ss-motion=""
                style={{
                  pointerEvents: "auto",
                  flex: "0 0 auto",
                  width: "100%",
                  boxShadow: PE.shDock,
                  display: "flex",
                  flexDirection: "column",
                  overflow: "hidden",
                  borderRadius: isMobile ? undefined : PE.rFloat,
                  color: PE.t3,
                  background: PE.panel,
                  border: isMobile ? "none" : `1px solid ${PE.line14}`,
                  borderTop: isMobile ? `1px solid ${PE.line14}` : undefined,
                  font: `12.5px/1.5 ${PE.ui}`,
                  // The one panel motion: a dock opens its own height while
                  // scaling up 3% from the corner it hangs off. It never
                  // slides in from off-screen and never overshoots.
                  transformOrigin: isMobile ? "bottom center" : "right top",
                  animation: `pe-dock-in ${PE.dMove} ${PE.ease} both`,
                }}
              >
                {/* HEADER — pinned, and the whole hit target when folded. */}
                <div
                  data-testid="dock-header"
                  role={foldable ? "button" : undefined}
                  tabIndex={foldable ? 0 : undefined}
                  aria-expanded={foldable ? isOpen : undefined}
                  onClick={foldable ? () => foldOne(id) : undefined}
                  onKeyDown={
                    foldable
                      ? (e) => {
                          if (e.key === "Enter" || e.key === " ") {
                            e.preventDefault();
                            foldOne(id);
                          }
                        }
                      : undefined
                  }
                  style={{
                    flex: "0 0 auto",
                    // Sticky inside the ONE column scroller: as the wheel
                    // carries you through a long dock, its header stays put
                    // until the next one pushes it out. That is what makes a
                    // tall stack navigable rather than an undifferentiated
                    // ribbon.
                    position: "sticky",
                    top: 0,
                    zIndex: 2,
                    display: "flex",
                    alignItems: "center",
                    gap: 8,
                    height: PE.hHead,
                    padding: "0 8px 0 12px",
                    cursor: foldable ? "pointer" : undefined,
                    // A folded header drops its fill and its bottom rule and
                    // dims its glyph and title one step. That is the whole
                    // difference; it never becomes a different component.
                    borderBottom: `1px solid ${isOpen ? PE.line06 : "transparent"}`,
                    // A sticky header sits OVER scrolling content, so it needs
                    // a real ground rather than a 1.5% wash.
                    background: isOpen
                      ? "linear-gradient(rgba(255,255,255,.015), rgba(255,255,255,.015)), var(--ss-ink-94)"
                      : "var(--ss-ink-94)",
                    transition: `background ${MOTION.state}, border-color ${MOTION.state}`,
                  }}
                >
                  <span
                    aria-hidden
                    className="ss-dock-glyph"
                    style={{
                      display: "inline-flex",
                      flex: "none",
                      color: isOpen ? PE.blue : PE.t5,
                      transition: `color ${MOTION.state}`,
                    }}
                  >
                    {tool.icon}
                  </span>
                  <span
                    style={{
                      flex: 1,
                      minWidth: 0,
                      fontSize: 11,
                      fontWeight: 600,
                      letterSpacing: ".1em",
                      textTransform: "uppercase",
                      color: isOpen ? PE.t3 : PE.t5,
                      overflow: "hidden",
                      textOverflow: "ellipsis",
                      whiteSpace: "nowrap",
                      transition: `color ${MOTION.state}`,
                    }}
                  >
                    {tool.label}
                  </span>
                  <div style={{ display: "flex", alignItems: "center", gap: 4 }}>
                    {foldable && (
                      <svg
                        viewBox="0 0 24 24"
                        width={12}
                        height={12}
                        aria-hidden
                        fill="none"
                        stroke={PE.t5}
                        strokeWidth={1.7}
                        strokeLinecap="round"
                        strokeLinejoin="round"
                        data-ss-motion=""
                        style={{
                          flex: "none",
                          transform: isOpen ? "rotate(0deg)" : "rotate(-90deg)",
                          transition: `transform ${MOTION.move}`,
                        }}
                      >
                        <path d="m6 9 6 6 6-6" />
                      </svg>
                    )}
                    {isOpen && canExpand && (
                      <button
                        type="button"
                        aria-label={isExpanded ? "Collapse report" : "Expand report"}
                        aria-pressed={isExpanded}
                        title={
                          isExpanded
                            ? "Collapse to the compact panel"
                            : "Expand to a large readable view (map stays visible)"
                        }
                        data-testid="dock-expand"
                        className="ss-headbtn pe-btn"
                        onClick={(e) => {
                          e.stopPropagation();
                          setExpanded((v) => !v);
                        }}
                        style={{
                          display: "inline-flex",
                          alignItems: "center",
                          justifyContent: "center",
                          width: 22,
                          height: 22,
                          borderRadius: 6,
                          background: "transparent",
                          border: "none",
                          color: PE.t5,
                          cursor: "pointer",
                          padding: 0,
                          lineHeight: 1,
                        }}
                      >
                        <svg
                          viewBox="0 0 24 24"
                          width={13}
                          height={13}
                          aria-hidden="true"
                          fill="none"
                          stroke="currentColor"
                          strokeWidth={1.7}
                          strokeLinecap="round"
                          strokeLinejoin="round"
                        >
                          {isExpanded ? (
                            <path d="M15 9h4m0 0V5m0 4-5-5M9 15H5m0 0v4m0-4 5 5" />
                          ) : (
                            <path d="M15 3h6m0 0v6m0-6-7 7M9 21H3m0 0v-6m0 6 7-7" />
                          )}
                        </svg>
                      </button>
                    )}
                    {/* The close control is SEPARATE from the header hit
                        target and must stopPropagation, or closing a folded
                        dock would expand it on the way out. */}
                    <button
                      type="button"
                      aria-label="Close"
                      data-testid="dock-close"
                      className="ss-headbtn pe-btn"
                      onClick={(e) => {
                        e.stopPropagation();
                        closeOne(id);
                      }}
                      style={{
                        display: "inline-flex",
                        alignItems: "center",
                        justifyContent: "center",
                        width: 22,
                        height: 22,
                        borderRadius: 6,
                        background: "transparent",
                        border: "none",
                        color: PE.t5,
                        cursor: "pointer",
                        lineHeight: 1,
                        padding: 0,
                      }}
                    >
                      <svg
                        viewBox="0 0 24 24"
                        width={13}
                        height={13}
                        aria-hidden="true"
                        fill="none"
                        stroke="currentColor"
                        strokeWidth={1.7}
                        strokeLinecap="round"
                      >
                        <path d="M18 6 6 18 M6 6l12 12" />
                      </svg>
                    </button>
                  </div>
                </div>

                {/* THE FOLD. The body animates its own height to zero and
                    back; the dock height follows it. 220ms of height and
                    140ms of opacity, on the one curve. */}
                {/* ONE SCROLLER IN THE COLUMN, not one per dock.
                    This body used to carry its own `overflow-y: auto` inside a
                    column that also scrolled. Two nested scrollers means the
                    inner one swallows the wheel and the outer never continues,
                    which is exactly why the stack did not read as one
                    continuous surface. The body now takes its natural height
                    and the COLUMN does all the scrolling, so a wheel gesture
                    carries from the first dock to the last without catching.
                    Except when BOXED: the expand-to-floating-box leaves the
                    column, so it is on its own and scrolls itself. */}
                <div
                  data-ss-motion=""
                  style={{
                    flex: "0 0 auto",
                    minHeight: 0,
                    maxHeight: isOpen ? 100000 : 0,
                    opacity: isOpen ? 1 : 0,
                    overflow: "hidden",
                    transition: `max-height ${MOTION.open}, opacity ${MOTION.state}`,
                  }}
                >
                  <div
                    className={undefined}
                    data-testid="dock-scroll"
                    style={{
                      maxHeight: "none",
                      overflowY: "visible",
                      WebkitOverflowScrolling: "touch",
                      padding: "14px 13px",
                    }}
                  >
                    {/* keyed on the tool AND the property: switching either
                        is a content change the eye should see arrive, not a
                        silent swap inside a panel that never moved. */}
                    <div
                      key={`${tool.id}:${activeParcelNodeId ?? "none"}`}
                      className="ss-rise"
                      data-ss-motion=""
                    >
                      <DockBody
                        tool={tool}
                        activeParcelNodeId={activeParcelNodeId}
                        closeDock={closeDock}
                        host={host}
                        prefix={tool.id === "brief" ? inspectSlot : null}
                      />
                    </div>
                  </div>
                </div>
              </section>
            );
          })}
        </div>
      )}
    </WorkbenchProvider>
  );
}

/** The dock's honest-state gate, then the tool's own content. */
function DockBody({
  tool,
  activeParcelNodeId,
  closeDock,
  host,
  prefix = null,
}: {
  tool: WorkbenchToolDef;
  activeParcelNodeId: string | null;
  closeDock: () => void;
  host: WorkbenchHostActions;
  prefix?: ReactNode;
}): ReactNode {
  // Registered-but-not-live: an HONEST coming state — never dead-looking UI.
  // Both branches below name WHAT IS MISSING AND WHAT WOULD FILL IT, which is
  // the whole contract of the honest-empty register.
  if (tool.status === "coming" || !tool.render) {
    return (
      <StateNote
        data-testid="dock-coming"
        register="nothing-yet"
        title={`${tool.label} is not wired up yet`}
        basis={
          <>
            It is registered on the workbench so the rail stays honest about
            what is coming, but nothing here is live. It arrives in a later
            build wave.
          </>
        }
      />
    );
  }
  // Property-scoped tool with no active property: honest, actionable state.
  if (tool.propertyScoped && !activeParcelNodeId) {
    return (
      <StateNote
        data-testid="dock-no-property"
        register="waiting"
        title="Select a property first"
        basis={
          <>
            Click a parcel on the map, or search an address or parcel id, and
            {" "}
            {tool.label.toLowerCase()} will scope to it.
          </>
        }
      />
    );
  }
  return (
    <>
      {prefix}
      {tool.render({ activeParcelNodeId, closeDock, host })}
    </>
  );
}
